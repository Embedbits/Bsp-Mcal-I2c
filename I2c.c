/** \brief Type representing time in picoseconds (timing calculation) */
typedef uint64_t i2c_TimePs_t;


/** \brief Type representing time in nanoseconds (I2C specification values) */
typedef uint32_t i2c_TimeNs_t;


/** \brief Type representing count of PCLK1 periods (CCR field, SCL phases) */
typedef uint32_t i2c_TimingCnt_t;


/** \brief Type representing encoded pin value (\ref i2c_SclPin_t / \ref i2c_SdaPin_t) */
typedef uint32_t i2c_PinCode_t;


/** \brief SCL generation options of I2C v1 (CCR register FS / DUTY) */
typedef enum
{
    I2C_SCL_MODE_STANDARD = 0u, /**< Standard-mode, tLOW / tHIGH = 1        */
    I2C_SCL_MODE_FAST_2,        /**< Fast-mode, tLOW / tHIGH = 2            */
    I2C_SCL_MODE_FAST_16_9,     /**< Fast-mode, tLOW / tHIGH = 16 / 9       */
    I2C_SCL_MODE_CNT            /**< Count of SCL generation options        */
}   i2c_SclMode_t;


/** \brief Timing characteristics of one SCL generation option */
typedef struct
{
    uint32_t        CcrMode;    /**< CCR register FS and DUTY bits                              */
    i2c_FreqHz_t    FreqMin;    /**< Lowest SCL frequency of the speed mode (exclusive)         */
    i2c_FreqHz_t    FreqMax;    /**< Highest SCL frequency of the speed mode                    */
    i2c_TimingCnt_t LowCycles;  /**< SCL low period in multiples of CCR x tPCLK1                */
    i2c_TimingCnt_t HighCycles; /**< SCL high period in multiples of CCR x tPCLK1               */
    i2c_TimingCnt_t CcrMin;     /**< Minimum CCR value (RM)                                     */
    i2c_TimeNs_t    SclLowMin;  /**< Minimum SCL low period (tLOW, I2C specification)           */
    i2c_TimeNs_t    SclHighMin; /**< Minimum SCL high period (tHIGH, I2C specification)         */
    i2c_TimeNs_t    RiseMax;    /**< Maximum SCL rise time (tr) used for TRISE                  */
}   i2c_SclCharac_t;


/** \brief Configuration of one I2C peripheral */
typedef struct
{
    I2C_TypeDef          *PeriphReg;    /**< Peripheral registers                        */
    rcc_PeriphId_t        PeriphRcc;    /**< RCC identification (APB1 clock)             */
    nvic_PeriphIrqList_t  PeriphEvNvic; /**< Event interrupt NVIC identification         */
    nvic_PeriphIrqList_t  PeriphErNvic; /**< Error interrupt NVIC identification         */
    nvic_IsrCallback_t    PeriphIsr;    /**< Interrupt service routine (event and error) */
}   i2c_PeriphConfigStruct_t;

