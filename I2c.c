/**
 * \brief Checks peripheral configuration structure (values in range, filters supported by the
 *        device, pins complete)
 *
 * \param i2cConfig [in]: Pointer to configuration structure
 *
 * \return Returns \ref I2C_REQUEST_OK if the configuration is valid. Otherwise returns
 *         \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Check_Config( const i2c_Config_t * const i2cConfig )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_NULL_PTR           != i2cConfig                ) &&
        ( I2C_PERIPH_CNT          > i2cConfig->PeriphId      ) &&
        ( I2C_CLK_SRC_CNT         > i2cConfig->ClkSrc        ) &&
        ( 0u                      < i2cConfig->BusFreq       ) &&
        ( I2C_BUS_FREQ_MAX_HZ    >= i2cConfig->BusFreq       ) &&
        ( I2C_ANALOG_FILTER_CNT   > i2cConfig->AnalogFilter  ) &&
        ( I2C_DIGITAL_FILTER_CNT  > i2cConfig->DigitalFilter ) &&
        ( I2C_ADDR_MODE_CNT       > i2cConfig->AddrMode      ) &&
        ( I2C_PIN_PULL_CNT        > i2cConfig->PinPull       )    )
    {
        const i2c_RequestState_t sclState = I2c_Check_Pin( i2cConfig->PeriphId, (i2c_PinCode_t)i2cConfig->SclPin, (i2c_PinCode_t)I2C_SCL_PIN_UNUSED );
        const i2c_RequestState_t sdaState = I2c_Check_Pin( i2cConfig->PeriphId, (i2c_PinCode_t)i2cConfig->SdaPin, (i2c_PinCode_t)I2C_SDA_PIN_UNUSED );

#if defined(I2C_FLTR_ANOFF)
        const i2c_RequestState_t fltState = I2C_REQUEST_OK;
#else
        i2c_RequestState_t fltState = I2C_REQUEST_ERROR;

        if( ( I2C_ANALOG_FILTER_DISABLED == i2cConfig->AnalogFilter  ) &&
            ( I2C_DIGITAL_FILTER_OFF     == i2cConfig->DigitalFilter )    )
        {
            fltState = I2C_REQUEST_OK;
        }
        else
        {
            /* Device has no configurable noise filters */
        }
#endif

        if( ( I2C_REQUEST_OK == sclState ) &&
            ( I2C_REQUEST_OK == sdaState ) &&
            ( I2C_REQUEST_OK == fltState )    )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            /* Pin configuration is incomplete or filter is not supported */
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks encoded SCL / SDA pin - unused pin or pin of the configured peripheral with
 *        valid port, pin and alternate function
 *
 * \param periphId   [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param pinCode    [in]: Encoded pin, value from \ref i2c_SclPin_t or \ref i2c_SdaPin_t
 * \param unusedCode [in]: Encoded value of unused pin (I2C_SCL_PIN_UNUSED / I2C_SDA_PIN_UNUSED)
 *
 * \return Returns \ref I2C_REQUEST_OK if the pin is unused or valid for the peripheral.
 *         Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Check_Pin( i2c_PeriphId_t periphId, i2c_PinCode_t pinCode, i2c_PinCode_t unusedCode )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    const i2c_PinCode_t pinPeriph = I2C_BIT_MASK_DECODE_PERIPH( pinCode );
    const i2c_PinCode_t pinPort   = I2C_BIT_MASK_DECODE_PORT( pinCode );
    const i2c_PinCode_t pinId     = I2C_BIT_MASK_DECODE_PIN( pinCode );
    const i2c_PinCode_t pinAf     = I2C_BIT_MASK_DECODE_AF( pinCode );

    if( unusedCode == pinCode )
    {
        /* Pin is not configured by the module */
        retState = I2C_REQUEST_OK;
    }
    else if( ( (i2c_PinCode_t)periphId          == pinPeriph ) &&
             ( (i2c_PinCode_t)GPIO_PORT_CNT      > pinPort   ) &&
             ( (i2c_PinCode_t)GPIO_PIN_ID_CNT    > pinId     ) &&
             ( (i2c_PinCode_t)GPIO_ALT_FUNC_CNT  > pinAf     )    )
    {
        retState = I2C_REQUEST_OK;
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks that the peripheral is disabled (PE = 0) - required for CCR / TRISE and FLTR
 *        change
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Returns \ref I2C_REQUEST_OK if the peripheral is disabled. Otherwise (or for an
 *         invalid periphId) returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Check_PeriphDisabled( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        const uint32_t periphEnabled = LL_I2C_IsEnabled( i2c_PeriphConf[ periphId ].PeriphReg );

        if( 0u == periphEnabled )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            /* Peripheral is enabled */
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks that no transfer is running and no START condition is pending
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Returns \ref I2C_REQUEST_OK if no transfer is running. Otherwise (or for an invalid
 *         periphId) returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Check_XferStopped( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        const uint32_t startPending = READ_BIT( i2c_PeriphConf[ periphId ].PeriphReg->CR1, I2C_CR1_START );

        if( ( I2C_FUNCTION_INACTIVE == i2c_XferContext[ periphId ].XferState ) &&
            ( 0u                    == startPending                          )    )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            /* Transfer is running */
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Waits (bounded) until the STOP condition requested by the previous transfer is sent
 *        (STOP bit is cleared by HW)
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Returns \ref I2C_REQUEST_OK if no STOP condition is pending. Otherwise returns
 *         \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Check_StopDone( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        I2C_TypeDef * const periphReg = i2c_PeriphConf[ periphId ].PeriphReg;

        for( i2c_TimeoutCnt_t iterationCnt = 0u; I2C_TIMEOUT_RAW > iterationCnt; iterationCnt ++ )
        {
            const uint32_t stopPending = READ_BIT( periphReg->CR1, I2C_CR1_STOP );

            if( 0u == stopPending )
            {
                retState = I2C_REQUEST_OK;
                break;
            }
            else
            {
                /* STOP condition is being generated, keep return state as error */
                retState = I2C_REQUEST_ERROR;
            }
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks transfer request - buffers of used directions and slave address range of the
 *        configured addressing mode
 *
 * \param periphId    [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param xferRequest [in]: Pointer to transfer request
 *
 * \return Returns \ref I2C_REQUEST_OK if the request is valid. Otherwise returns
 *         \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Check_XferRequest( i2c_PeriphId_t periphId, const i2c_XferRequest_t * const xferRequest )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;
    i2c_AddrMode_t     addrMode = I2C_ADDR_MODE_7BIT;

    if( I2C_NULL_PTR != xferRequest )
    {
        retState = I2c_Get_AddrMode( periphId, &addrMode );
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    if( I2C_REQUEST_OK == retState )
    {
        if( ( i2c_SlaveAddrMaxLut[ addrMode ] >= xferRequest->SlaveAddr                                  ) &&
            ( ( 0u == xferRequest->TxSize ) || ( I2C_NULL_PTR != xferRequest->TxData )                   ) &&
            ( ( 0u == xferRequest->RxSize ) || ( I2C_NULL_PTR != xferRequest->RxData )                   )    )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            /* Slave address out of range or missing buffer */
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks data handling configuration (common part and transfer mode specific part)
 *
 * \param periphId   [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param dataConfig [in]: Pointer to data handling configuration
 *
 * \return Returns \ref I2C_REQUEST_OK if the configuration is valid. Otherwise returns
 *         \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Check_DataConfig( i2c_PeriphId_t periphId, const i2c_DataConfig_t * const dataConfig )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT     > periphId             ) &&
        ( I2C_NULL_PTR      != dataConfig           ) &&
        ( I2C_XFER_MODE_CNT  > dataConfig->XferMode )    )
    {
        retState = i2c_XferModeLut[ dataConfig->XferMode ].CheckConfig( periphId, dataConfig );
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Enables / disables the peripheral (PE) with read-back verification
 *
 * \param periphId    [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param enableState [in]: Required state, value from \ref i2c_FunctionState_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_Enable( i2c_PeriphId_t periphId, i2c_FunctionState_t enableState )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        uint32_t peBit = 0u;

        if( I2C_FUNCTION_ACTIVE == enableState )
        {
            peBit = I2C_CR1_PE;
        }
        else
        {
            /* PE = 0 */
        }

        retState = I2c_Set_RegValue( &i2c_PeriphConf[ periphId ].PeriphReg->CR1, I2C_CR1_PE, peBit );
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Configures SCL / SDA pin as open-drain alternate function (GPIO port clock is enabled by
 *        Gpio_Init())
 *
 * \param periphId   [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param pinCode    [in]: Encoded pin, value from \ref i2c_SclPin_t or \ref i2c_SdaPin_t.
 *                         Unused pin is skipped.
 * \param unusedCode [in]: Encoded value of unused pin (I2C_SCL_PIN_UNUSED / I2C_SDA_PIN_UNUSED)
 * \param pinPull    [in]: Pull resistor configuration, value from \ref i2c_PinPull_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_Pin( i2c_PeriphId_t periphId, i2c_PinCode_t pinCode, i2c_PinCode_t unusedCode, i2c_PinPull_t pinPull )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    retState = I2c_Check_Pin( periphId, pinCode, unusedCode );

    if( ( I2C_REQUEST_OK   == retState ) &&
        ( I2C_PIN_PULL_CNT  > pinPull  )    )
    {
        if( unusedCode != pinCode )
        {
            gpio_Config_t gpioConfig;

            gpioConfig.PortId         = (gpio_PortId_t)I2C_BIT_MASK_DECODE_PORT( pinCode );
            gpioConfig.PinId          = (gpio_PinId_t)I2C_BIT_MASK_DECODE_PIN( pinCode );
            gpioConfig.PinMode        = GPIO_PIN_MODE_ALTERNATE;
            gpioConfig.PinPull        = i2c_PinPullLut[ pinPull ];
            gpioConfig.PinSpeed       = GPIO_PIN_SPEED_LOW;
            gpioConfig.PinOutType     = GPIO_PIN_OUTPUT_OPENDRAIN;
            gpioConfig.PinAltFunction = (gpio_AltFunction_t)I2C_BIT_MASK_DECODE_AF( pinCode );
            gpioConfig.PinActiveLevel = GPIO_PIN_LEVEL_HIGH;

            /* Port clock activation, pin configuration and read-back verification is done by Gpio_Init() */
            const gpio_RequestState_t gpioState = Gpio_Init( &gpioConfig );

            if( GPIO_REQUEST_OK == gpioState )
            {
                retState = I2C_REQUEST_OK;
            }
            else
            {
                retState = I2C_REQUEST_ERROR;
            }
        }
        else
        {
            /* Pin is not configured by the module */
            retState = I2C_REQUEST_OK;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Writes register field with read-back verification
 *
 * \note  The register is not written if the field already has the value - read-modify-write of
 *        CR1 while STOP is pending could set STOP again after HW cleared it (STOP would then
 *        stay pending without master mode and block the next transfer).
 *
 * \param regAddr  [in]: Address of the register
 * \param regMask  [in]: Mask of the modified bits
 * \param regValue [in]: Value of the modified bits (bits out of the mask are ignored)
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if the value was applied.
 *         Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_RegValue( volatile uint32_t * const regAddr, uint32_t regMask, uint32_t regValue )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;
    const uint32_t     expected = regValue & regMask;

    if( expected != READ_BIT( *regAddr, regMask ) )
    {
        MODIFY_REG( *regAddr, regMask, expected );
    }
    else
    {
        /* Field has already the required value */
    }

    for( i2c_TimeoutCnt_t iterationCnt = 0u; I2C_TIMEOUT_RAW > iterationCnt; iterationCnt ++ )
    {
        const uint32_t readValue = READ_BIT( *regAddr, regMask );

        if( expected == readValue )
        {
            retState = I2C_REQUEST_OK;
            break;
        }
        else
        {
            /* Value has not yet been applied, keep return state as error */
            retState = I2C_REQUEST_ERROR;
        }
    }

    return ( retState );
}


/**
 * \brief Returns frequency of the I2C clock (PCLK1)
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param clkFreq [out]: Pointer to store the frequency in Hz. Must not be NULL.
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems (non-zero frequency). Otherwise returns
 *         \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Get_PeriphClk( i2c_PeriphId_t periphId, i2c_FreqHz_t * const clkFreq )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT > periphId ) &&
        ( I2C_NULL_PTR  != clkFreq  )    )
    {
        rcc_FreqHz_t             rccFreq  = 0u;
        const rcc_RequestState_t rccState = Rcc_Get_PeriphClk( i2c_PeriphConf[ periphId ].PeriphRcc, &rccFreq );

        if( ( RCC_REQUEST_OK == rccState ) &&
            ( 0u              < rccFreq  )    )
        {
            *clkFreq = (i2c_FreqHz_t)rccFreq;
            retState = I2C_REQUEST_OK;
        }
        else
        {
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Calculates CCR and TRISE register values (RM "I2C_CCR", "I2C_TRISE")
 *
 * For every SCL generation option of the speed mode the smallest CCR is derived from the
 * required frequency (rounded up - frequency is never exceeded), from the CCR minimum and from
 * the minimum SCL low / high periods of the I2C specification. The option with the highest
 * resulting frequency is used, the frequency must be within I2C_BUS_FREQ_TOLERANCE_PCT.
 * TRISE = tr(max) / tPCLK1 + 1 (1000 ns Standard-mode, 300 ns Fast-mode).
 *
 * \param clkFreq   [in]: PCLK1 frequency in Hz
 * \param busFreq   [in]: Required SCL frequency in Hz (1 - \ref I2C_BUS_FREQ_MAX_HZ)
 * \param ccrReg   [out]: Pointer to store CCR value (FS, DUTY, CCR). Must not be NULL.
 * \param triseReg [out]: Pointer to store TRISE value. Must not be NULL.
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if valid timing was found.
 *         Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Get_ClkRegs( i2c_FreqHz_t clkFreq, i2c_FreqHz_t busFreq, uint32_t * const ccrReg, uint32_t * const triseReg )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    const i2c_FreqHz_t clkMhz = clkFreq / I2C_HZ_PER_MHZ;

    if( ( I2C_NULL_PTR        != ccrReg   ) &&
        ( I2C_NULL_PTR        != triseReg ) &&
        ( 0u                   < busFreq  ) &&
        ( I2C_BUS_FREQ_MAX_HZ >= busFreq  ) &&
        ( I2C_PCLK_MHZ_MIN    <= clkMhz   ) &&
        ( I2C_PCLK_MHZ_MAX    >= clkMhz   )    )
    {
        const i2c_TimePs_t clkPeriod = I2C_PS_PER_S / clkFreq;
        const i2c_FreqHz_t freqMin   = busFreq - ( ( busFreq * I2C_BUS_FREQ_TOLERANCE_PCT ) / I2C_PERCENT );
        i2c_FreqHz_t       bestFreq  = 0u;

        for( i2c_SclMode_t modeIdx = I2C_SCL_MODE_STANDARD; I2C_SCL_MODE_CNT > modeIdx; modeIdx ++ )
        {
            const i2c_SclCharac_t * const charac = &i2c_SclCharacLut[ modeIdx ];

            if( ( charac->FreqMin < busFreq ) &&
                ( charac->FreqMax >= busFreq ) &&
                ( ( I2C_SCL_MODE_STANDARD == modeIdx ) || ( I2C_PCLK_MHZ_FAST_MIN <= clkMhz ) ) )
            {
                const i2c_TimingCnt_t sclCycles = charac->LowCycles + charac->HighCycles;
                const i2c_TimingCnt_t ccrFreq   = (i2c_TimingCnt_t)I2C_DIV_ROUND_UP( (uint64_t)clkFreq, (uint64_t)sclCycles * busFreq );
                const i2c_TimingCnt_t ccrLow    = (i2c_TimingCnt_t)I2C_DIV_ROUND_UP( (i2c_TimePs_t)charac->SclLowMin  * I2C_PS_PER_NS, (i2c_TimePs_t)charac->LowCycles  * clkPeriod );
                const i2c_TimingCnt_t ccrHigh   = (i2c_TimingCnt_t)I2C_DIV_ROUND_UP( (i2c_TimePs_t)charac->SclHighMin * I2C_PS_PER_NS, (i2c_TimePs_t)charac->HighCycles * clkPeriod );
                i2c_TimingCnt_t       ccrValue  = charac->CcrMin;

                if( ccrFreq > ccrValue )
                {
                    ccrValue = ccrFreq;
                }
                else
                {
                    /* CCR minimum limits the frequency */
                }

                if( ccrLow > ccrValue )
                {
                    ccrValue = ccrLow;
                }
                else
                {
                    /* SCL low period is fulfilled */
                }

                if( ccrHigh > ccrValue )
                {
                    ccrValue = ccrHigh;
                }
                else
                {
                    /* SCL high period is fulfilled */
                }

                const i2c_FreqHz_t sclFreq = clkFreq / ( sclCycles * ccrValue );

                if( ( I2C_CCR_MAX >= ccrValue ) &&
                    ( freqMin     <= sclFreq  ) &&
                    ( bestFreq     < sclFreq  )    )
                {
                    bestFreq  = sclFreq;
                    *ccrReg   = charac->CcrMode | ccrValue;
                    *triseReg = ( ( charac->RiseMax * clkMhz ) / I2C_NS_PER_US ) + I2C_TRISE_OFFSET;
                    retState  = I2C_REQUEST_OK;
                }
                else
                {
                    /* Option out of CCR range, out of tolerance or not better than a previous one */
                }
            }
            else
            {
                /* Option does not belong to the speed mode of the frequency */
            }
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Initializes data handling - configuration is copied, transfer mode resources are
 *        initialized and I2C interrupts are enabled in NVIC (DMA / ISR mode)
 *
 * \note  On failure the partially initialized data handling is released.
 *
 * \param periphId   [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param dataConfig [in]: Pointer to checked data handling configuration
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_XferInit( i2c_PeriphId_t periphId, const i2c_DataConfig_t * const dataConfig )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT     > periphId             ) &&
        ( I2C_NULL_PTR      != dataConfig           ) &&
        ( I2C_XFER_MODE_CNT  > dataConfig->XferMode )    )
    {
        i2c_XferContext_t * const xferCtx = &i2c_XferContext[ periphId ];

        xferCtx->Config    = *dataConfig;
        xferCtx->XferState = I2C_FUNCTION_INACTIVE;
        xferCtx->XferError = I2C_XFER_ERROR_NONE;
        xferCtx->InitState = I2C_FUNCTION_ACTIVE;

        retState = i2c_XferModeLut[ dataConfig->XferMode ].Init( periphId );

        const i2c_FunctionState_t irqUsed = I2c_Get_IrqUsed( dataConfig );

        if( ( I2C_REQUEST_OK      == retState ) &&
            ( I2C_FUNCTION_ACTIVE == irqUsed  )    )
        {
            retState = I2c_Set_IrqInit( periphId, dataConfig->IrqPriority );
        }
        else
        {
            /* Mode initialization failed or interrupts are not used */
        }

        if( I2C_REQUEST_OK != retState )
        {
            (void)I2c_Set_XferDeinit( periphId );
        }
        else
        {
            /* Data handling is initialized */
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Deinitializes data handling - running transfer is aborted, transfer mode resources are
 *        released and I2C interrupts are disabled in NVIC
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems (also if data handling was not initialized).
 *         Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_XferDeinit( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        i2c_XferContext_t * const xferCtx = &i2c_XferContext[ periphId ];

        if( I2C_FUNCTION_ACTIVE == xferCtx->InitState )
        {
            i2c_RequestState_t abortState = I2C_REQUEST_OK;

            if( I2C_FUNCTION_ACTIVE == xferCtx->XferState )
            {
                abortState = I2c_Set_XferAbort( periphId );
            }
            else
            {
                /* No transfer is running */
            }

            const i2c_RequestState_t deinitState = i2c_XferModeLut[ xferCtx->Config.XferMode ].Deinit( periphId );
            const i2c_RequestState_t irqState    = I2c_Set_IrqDeinit( periphId );

            xferCtx->InitState = I2C_FUNCTION_INACTIVE;

            if( ( I2C_REQUEST_OK == abortState  ) &&
                ( I2C_REQUEST_OK == deinitState ) &&
                ( I2C_REQUEST_OK == irqState    )    )
            {
                retState = I2C_REQUEST_OK;
            }
            else
            {
                retState = I2C_REQUEST_ERROR;
            }
        }
        else
        {
            /* Data handling is not initialized */
            retState = I2C_REQUEST_OK;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Returns if the data handling configuration uses I2C interrupts (DMA or ISR mode)
 *
 * \param dataConfig [in]: Pointer to data handling configuration
 *
 * \return \ref I2C_FUNCTION_ACTIVE if I2C interrupts are used, otherwise \ref I2C_FUNCTION_INACTIVE
 */
static i2c_FunctionState_t I2c_Get_IrqUsed( const i2c_DataConfig_t * const dataConfig )
{
    i2c_FunctionState_t irqUsed = I2C_FUNCTION_INACTIVE;

    if( ( I2C_NULL_PTR != dataConfig ) &&
        ( ( I2C_XFER_MODE_DMA == dataConfig->XferMode ) ||
          ( I2C_XFER_MODE_ISR == dataConfig->XferMode )    )    )
    {
        irqUsed = I2C_FUNCTION_ACTIVE;
    }
    else
    {
        irqUsed = I2C_FUNCTION_INACTIVE;
    }

    return ( irqUsed );
}


/**
 * \brief Registers the interrupt handler, configures priority and enables I2C event and error
 *        interrupt in NVIC
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param irqPrio  [in]: Interrupt priority
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_IrqInit( i2c_PeriphId_t periphId, i2c_IrqPrio_t irqPrio )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        const i2c_PeriphConfigStruct_t * const periphConf = &i2c_PeriphConf[ periphId ];

        const nvic_RequestState_t evHandlerState = Nvic_Set_PeriphIrq_Handler( periphConf->PeriphEvNvic, periphConf->PeriphIsr );
        const nvic_RequestState_t erHandlerState = Nvic_Set_PeriphIrq_Handler( periphConf->PeriphErNvic, periphConf->PeriphIsr );
        const i2c_RequestState_t  prioState      = I2c_Set_IrqPriority( periphId, irqPrio );
        const nvic_RequestState_t evActState     = Nvic_Set_PeriphIrq_Active( periphConf->PeriphEvNvic );
        const nvic_RequestState_t erActState     = Nvic_Set_PeriphIrq_Active( periphConf->PeriphErNvic );

        if( ( NVIC_REQUEST_OK == evHandlerState ) &&
            ( NVIC_REQUEST_OK == erHandlerState ) &&
            ( I2C_REQUEST_OK  == prioState      ) &&
            ( NVIC_REQUEST_OK == evActState     ) &&
            ( NVIC_REQUEST_OK == erActState     )    )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Disables I2C event and error interrupt in NVIC
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_IrqDeinit( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        const nvic_RequestState_t evState = Nvic_Set_PeriphIrq_Inactive( i2c_PeriphConf[ periphId ].PeriphEvNvic );
        const nvic_RequestState_t erState = Nvic_Set_PeriphIrq_Inactive( i2c_PeriphConf[ periphId ].PeriphErNvic );

        if( ( NVIC_REQUEST_OK == evState ) &&
            ( NVIC_REQUEST_OK == erState )    )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief START condition sent (SB) - address byte (7-bit) or header (10-bit) is written to DR,
 *        which clears SB (SR1 was read by the caller)
 *
 * - 7-bit: address with the direction of the running phase
 * - 10-bit write phase or 10-bit read before the read header: 11110xx0, ADD10 follows
 * - 10-bit read after repeated START: 11110xx1, ADDR follows
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_XferAddrByte( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        const i2c_XferContext_t * const xferCtx   = &i2c_XferContext[ periphId ];
        const uint32_t                  slaveAddr = (uint32_t)xferCtx->Request.SlaveAddr;
        uint32_t                        addrByte  = 0u;

        if( I2C_ADDR_MODE_7BIT == i2c_AddrModeState[ periphId ] )
        {
            addrByte = slaveAddr << I2C_SLAVE_ADDR_7BIT_SHIFT;

            if( I2C_XFER_PHASE_READ == xferCtx->Phase )
            {
                addrByte |= I2C_ADDR_BYTE_READ;
            }
            else
            {
                /* Write direction */
            }
        }
        else
        {
            addrByte = I2C_ADDR10_HEADER | ( ( slaveAddr >> I2C_ADDR10_HEADER_SHIFT ) & I2C_ADDR10_HEADER_MASK );

            if( ( I2C_XFER_PHASE_READ   == xferCtx->Phase         ) &&
                ( I2C_FUNCTION_INACTIVE == xferCtx->Addr10Restart )    )
            {
                /* Read header after repeated START - the full address was already sent */
                addrByte |= I2C_ADDR_BYTE_READ;
            }
            else
            {
                /* Write header - second address byte follows (ADD10) */
            }
        }

        LL_I2C_TransmitData8( i2c_PeriphConf[ periphId ].PeriphReg, (uint8_t)addrByte );

        retState = I2C_REQUEST_OK;
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Address acknowledged (ADDR) - acknowledge control of the read phase is prepared and ADDR
 *        is cleared (SR1 read by the caller, SR2 read here); SCL is stretched until then
 *
 * - 10-bit read: address was sent in write direction - repeated START for the read header
 * - address only transfer: STOP, transfer complete
 * - write phase: data follow (TXE)
 * - read phase by DMA: ACK, NACK of the last byte by LAST
 * - read 1 byte: NACK, ADDR cleared, STOP (RXNE ends the transfer)
 * - read 2 bytes: NACK with POS (NACK of the second byte), BTF reads both bytes
 * - read 3 and more bytes: ACK, NACK of the last byte is programmed by BTF of N-2
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_XferAddrDone( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        I2C_TypeDef * const       periphReg = i2c_PeriphConf[ periphId ].PeriphReg;
        i2c_XferContext_t * const xferCtx   = &i2c_XferContext[ periphId ];
        i2c_FunctionState_t       dmaRxUsed = I2C_FUNCTION_INACTIVE;

        retState = I2c_Get_DmaRxUsed( periphId, &dmaRxUsed );

        if( I2C_FUNCTION_INACTIVE == xferCtx->Addr10Restart )
        {
            /* Address of the running phase acknowledged - its data flags are valid from now */
            xferCtx->AddrAcked = I2C_FUNCTION_ACTIVE;
        }
        else
        {
            /* Write direction address of a 10-bit read - the read phase address follows */
        }

        if( I2C_REQUEST_OK != retState )
        {
            /* Invalid peripheral identification */
        }
        else if( I2C_FUNCTION_ACTIVE == xferCtx->Addr10Restart )
        {
            /* 10-bit address sent in write direction - read header follows the repeated START */
            xferCtx->Addr10Restart = I2C_FUNCTION_INACTIVE;

            LL_I2C_ClearFlag_ADDR( periphReg );
            LL_I2C_GenerateStartCondition( periphReg );
        }
        else if( I2C_XFER_PHASE_WRITE == xferCtx->Phase )
        {
            LL_I2C_ClearFlag_ADDR( periphReg );

            if( ( 0u == xferCtx->Request.TxSize ) &&
                ( 0u == xferCtx->Request.RxSize )    )
            {
                /* Address only transfer - slave acknowledged */
                LL_I2C_GenerateStopCondition( periphReg );

                retState = I2c_Set_XferEnd( periphId, I2C_XFER_ERROR_NONE );
            }
            else
            {
                /* Data bytes follow (TXE) */
                retState = I2c_Set_BufIrq( periphId, I2c_Get_SwData( periphId ) );
            }
        }
        else if( I2C_FUNCTION_ACTIVE == dmaRxUsed )
        {
            /* All bytes acknowledged except the last one (LAST) */
            retState = I2c_Set_Ack( periphId, I2C_CR1_ACK );

            LL_I2C_ClearFlag_ADDR( periphReg );
        }
        else if( 1u == xferCtx->Request.RxSize )
        {
            /* Single byte: NACK before ADDR is cleared, STOP right after it */
            retState = I2c_Set_Ack( periphId, 0u );

            LL_I2C_ClearFlag_ADDR( periphReg );
            LL_I2C_GenerateStopCondition( periphReg );

            if( I2C_REQUEST_OK == retState )
            {
                retState = I2c_Set_BufIrq( periphId, I2C_FUNCTION_ACTIVE );
            }
            else
            {
                /* Acknowledge control failed */
            }
        }
        else if( I2C_RX_LAST_BYTES == xferCtx->Request.RxSize )
        {
            /* Two bytes: POS - NACK applies to the second byte, both bytes are read on BTF */
            retState = I2c_Set_Ack( periphId, I2C_CR1_POS );

            LL_I2C_ClearFlag_ADDR( periphReg );

            if( I2C_REQUEST_OK == retState )
            {
                retState = I2c_Set_BufIrq( periphId, I2C_FUNCTION_INACTIVE );
            }
            else
            {
                /* Acknowledge control failed */
            }
        }
        else
        {
            /* Three and more bytes: ACK, NACK is programmed on BTF of the byte N-2 */
            retState = I2c_Set_Ack( periphId, I2C_CR1_ACK );

            LL_I2C_ClearFlag_ADDR( periphReg );

            if( ( I2C_REQUEST_OK     == retState                ) &&
                ( I2C_RX_BTF_BYTES    < xferCtx->Request.RxSize )    )
            {
                retState = I2c_Set_BufIrq( periphId, I2C_FUNCTION_ACTIVE );
            }
            else if( I2C_REQUEST_OK == retState )
            {
                /* Three bytes - the first byte is read on BTF */
                retState = I2c_Set_BufIrq( periphId, I2C_FUNCTION_INACTIVE );
            }
            else
            {
                /* Acknowledge control failed */
            }
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Data step of the write phase - next byte is written to DR (TXE, software modes), end of
 *        the phase is processed on BTF after all bytes were written (STOP or repeated START of the
 *        read phase)
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param isrFlags [in]: Snapshot of I2C SR1 register
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_XferWriteStep( i2c_PeriphId_t periphId, i2c_IsrFlags_t isrFlags )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        I2C_TypeDef * const       periphReg = i2c_PeriphConf[ periphId ].PeriphReg;
        i2c_XferContext_t * const xferCtx   = &i2c_XferContext[ periphId ];
        const i2c_RequestState_t  txDone    = i2c_XferModeLut[ xferCtx->Config.XferMode ].CheckTxDone( periphId );

        retState = I2C_REQUEST_OK;

        if( I2C_REQUEST_OK != txDone )
        {
            const i2c_DataCnt_t txIdx = xferCtx->TxIdx;

            if( ( I2C_FUNCTION_ACTIVE == I2c_Get_SwData( periphId ) ) &&
                ( 0u                  != ( I2C_SR1_TXE & isrFlags ) ) &&
                ( xferCtx->Request.TxSize > txIdx                   )    )
            {
                /* Writing of DR clears TXE (and BTF) */
                LL_I2C_TransmitData8( periphReg, xferCtx->Request.TxData[ txIdx ] );
                xferCtx->TxIdx = txIdx + 1u;

                if( xferCtx->Request.TxSize == xferCtx->TxIdx )
                {
                    /* Last byte written - end of the phase is signaled by BTF */
                    retState = I2c_Set_BufIrq( periphId, I2C_FUNCTION_INACTIVE );
                }
                else
                {
                    /* Next byte on TXE */
                }
            }
            else
            {
                /* Bytes are moved by DMA or data register is not empty */
            }
        }
        else if( 0u != ( I2C_SR1_BTF & isrFlags ) )
        {
            if( 0u < xferCtx->Request.RxSize )
            {
                /* Read phase - repeated START (clears BTF once it is sent), acknowledge control is
                 * set on ADDR, flags of the write phase are ignored until then */
                xferCtx->Phase     = I2C_XFER_PHASE_READ;
                xferCtx->AddrAcked = I2C_FUNCTION_INACTIVE;

                LL_I2C_GenerateStartCondition( periphReg );
            }
            else
            {
                /* Last byte was sent - STOP condition ends the transfer */
                LL_I2C_GenerateStopCondition( periphReg );

                retState = I2c_Set_XferEnd( periphId, I2C_XFER_ERROR_NONE );
            }
        }
        else
        {
            /* Last byte is being transmitted */
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Data step of the read phase moved by software (RM reception procedure based on BTF)
 *
 * - more than 3 bytes remaining: RXNE - one byte is read
 * - 3 bytes remaining: BTF (N-2 in DR, N-1 in shift register) - NACK is programmed, N-2 is read
 * - 2 bytes remaining: BTF (N-1 in DR, N in shift register) - STOP, both bytes are read
 * - 1 byte (single byte transfer): RXNE - byte is read (STOP was programmed on ADDR)
 *
 * \note  Read phase moved by DMA ends by the transfer complete interrupt of the stream - I2C
 *        events of the phase are ignored.
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param isrFlags [in]: Snapshot of I2C SR1 register
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_XferReadStep( i2c_PeriphId_t periphId, i2c_IsrFlags_t isrFlags )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        I2C_TypeDef * const       periphReg = i2c_PeriphConf[ periphId ].PeriphReg;
        i2c_XferContext_t * const xferCtx   = &i2c_XferContext[ periphId ];
        const i2c_DataCnt_t       rxIdx     = xferCtx->RxIdx;
        const i2c_DataCnt_t       remaining = xferCtx->Request.RxSize - rxIdx;
        const uint32_t            rxne      = isrFlags & I2C_SR1_RXNE;
        const uint32_t            btf       = isrFlags & I2C_SR1_BTF;

        retState = I2C_REQUEST_OK;

        if( ( I2C_FUNCTION_ACTIVE != I2c_Get_SwData( periphId ) ) ||
            ( rxIdx               >= xferCtx->Request.RxSize    )    )
        {
            /* Bytes are moved by DMA or all bytes were read */
        }
        else if( ( I2C_RX_BTF_BYTES < remaining ) && ( 0u != rxne ) )
        {
            /* Reading of DR clears RXNE */
            xferCtx->Request.RxData[ rxIdx ] = LL_I2C_ReceiveData8( periphReg );
            xferCtx->RxIdx                   = rxIdx + 1u;

            if( I2C_RX_BTF_BYTES == ( remaining - 1u ) )
            {
                /* Last three bytes are handled by BTF */
                retState = I2c_Set_BufIrq( periphId, I2C_FUNCTION_INACTIVE );
            }
            else
            {
                /* Next byte on RXNE */
            }
        }
        else if( ( I2C_RX_BTF_BYTES == remaining ) && ( 0u != btf ) )
        {
            /* NACK of the last byte, byte N-2 is read (the stretched SCL is released) */
            retState = I2c_Set_Ack( periphId, 0u );

            xferCtx->Request.RxData[ rxIdx ] = LL_I2C_ReceiveData8( periphReg );
            xferCtx->RxIdx                   = rxIdx + 1u;
        }
        else if( ( I2C_RX_LAST_BYTES == remaining ) && ( 0u != btf ) )
        {
            /* POS cleared before STOP (no CR1 write while STOP is pending), STOP before the last
             * two bytes are read from DR and shift register */
            retState = I2c_Set_Ack( periphId, 0u );

            LL_I2C_GenerateStopCondition( periphReg );

            xferCtx->Request.RxData[ rxIdx ]      = LL_I2C_ReceiveData8( periphReg );
            xferCtx->Request.RxData[ rxIdx + 1u ] = LL_I2C_ReceiveData8( periphReg );
            xferCtx->RxIdx                        = rxIdx + I2C_RX_LAST_BYTES;

            retState = I2c_Set_XferEnd( periphId, I2C_XFER_ERROR_NONE );
        }
        else if( ( 1u == remaining ) && ( 0u != rxne ) )
        {
            /* Single byte transfer - NACK and STOP were programmed on ADDR */
            xferCtx->Request.RxData[ rxIdx ] = LL_I2C_ReceiveData8( periphReg );
            xferCtx->RxIdx                   = rxIdx + 1u;

            retState = I2c_Set_XferEnd( periphId, I2C_XFER_ERROR_NONE );
        }
        else
        {
            /* Waiting for the event of the reception step */
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Ends the running transfer - transfer mode resources are stopped, acknowledge control is
 *        reset and XferCompleteCallback / ErrorCallback is called
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param errorId  [in]: Result of the transfer, value from \ref i2c_XferErrorId_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_XferEnd( i2c_PeriphId_t periphId, i2c_XferErrorId_t errorId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT     > periphId ) &&
        ( I2C_XFER_ERROR_CNT > errorId  )    )
    {
        i2c_XferContext_t * const      xferCtx  = &i2c_XferContext[ periphId ];
        const i2c_XferModeIf_t * const modeIf   = &i2c_XferModeLut[ xferCtx->Config.XferMode ];
        i2c_XferErrorId_t              xferErr  = errorId;

        const i2c_RequestState_t doneState = modeIf->CheckDone( periphId );
        const i2c_RequestState_t stopState = modeIf->Stop( periphId );
        const i2c_RequestState_t ackState  = I2c_Set_Ack( periphId, 0u );

        if( ( I2C_XFER_ERROR_NONE == xferErr   ) &&
            ( I2C_REQUEST_OK      != doneState )    )
        {
            /* Transfer was finished, but DMA did not move all bytes */
            xferErr = I2C_XFER_ERROR_DMA_TRANSFER;
        }
        else
        {
            /* Result is kept */
        }

        xferCtx->XferError = xferErr;
        xferCtx->XferState = I2C_FUNCTION_INACTIVE;

        if( I2C_XFER_ERROR_NONE == xferErr )
        {
            if( I2C_NULL_PTR != xferCtx->Config.XferCompleteCallback )
            {
                xferCtx->Config.XferCompleteCallback( );
            }
            else
            {
                /* Transfer complete callback is not used */
            }
        }
        else
        {
            if( I2C_NULL_PTR != xferCtx->Config.ErrorCallback )
            {
                xferCtx->Config.ErrorCallback( xferErr );
            }
            else
            {
                /* Error callback is not used */
            }
        }

        if( ( I2C_REQUEST_OK == stopState ) &&
            ( I2C_REQUEST_OK == ackState  )    )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Aborts the running transfer without callback - transfer mode resources are stopped and
 *        the peripheral is reset by software reset (if it was enabled)
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_XferAbort( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        i2c_XferContext_t * const xferCtx    = &i2c_XferContext[ periphId ];
        const uint32_t            periphEn   = LL_I2C_IsEnabled( i2c_PeriphConf[ periphId ].PeriphReg );
        const i2c_RequestState_t  stopState  = i2c_XferModeLut[ xferCtx->Config.XferMode ].Stop( periphId );
        i2c_RequestState_t        resetState = I2C_REQUEST_OK;

        xferCtx->XferState = I2C_FUNCTION_INACTIVE;

        if( 0u != periphEn )
        {
            /* Software reset - bus lines are released, state machines and flags are reset */
            resetState = I2c_Set_PeriphReset( periphId );
        }
        else
        {
            /* Peripheral is disabled, communication is already released */
        }

        if( ( I2C_REQUEST_OK == stopState  ) &&
            ( I2C_REQUEST_OK == resetState )    )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            retState = I2C_REQUEST_ERROR;
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Software reset of the peripheral (SWRST) - I2C state machine, flags and all registers
 *        are reset, the configuration (CR2 FREQ, CCR, TRISE, FLTR, OAR1) is restored and the
 *        peripheral is enabled again
 *
 * \note  Clearing of PE does not reset a running communication on I2C v1 (PE is cleared at the
 *        end of the communication) - SWRST releases the bus lines immediately.
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_PeriphReset( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        I2C_TypeDef * const periphReg = i2c_PeriphConf[ periphId ].PeriphReg;
        const uint32_t      freqReg   = READ_BIT( periphReg->CR2, I2C_CR2_FREQ );
        const uint32_t      ccrReg    = READ_REG( periphReg->CCR );
        const uint32_t      triseReg  = READ_REG( periphReg->TRISE );
        const uint32_t      oar1Reg   = READ_REG( periphReg->OAR1 );
#if defined(I2C_FLTR_ANOFF)
        const uint32_t      fltrReg   = READ_REG( periphReg->FLTR );
#endif

        retState = I2c_Set_RegValue( &periphReg->CR1, I2C_CR1_SWRST, I2C_CR1_SWRST );

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->CR1, I2C_CR1_SWRST, 0u );
        }
        else
        {
            /* Software reset could not be entered */
        }

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->CR2, I2C_CR2_FREQ, freqReg );
        }
        else
        {
            /* Software reset could not be left */
        }

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->CCR, ( I2C_CCR_FS | I2C_CCR_DUTY | I2C_CCR_CCR ), ccrReg );
        }
        else
        {
            /* Configuration could not be restored */
        }

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->TRISE, I2C_TRISE_TRISE, triseReg );
        }
        else
        {
            /* Configuration could not be restored */
        }

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->OAR1, oar1Reg, oar1Reg );
        }
        else
        {
            /* Configuration could not be restored */
        }

#if defined(I2C_FLTR_ANOFF)
        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->FLTR, ( I2C_FLTR_ANOFF | I2C_FLTR_DNF ), fltrReg );
        }
        else
        {
            /* Configuration could not be restored */
        }
#endif

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_Enable( periphId, I2C_FUNCTION_ACTIVE );
        }
        else
        {
            /* Configuration could not be restored */
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Enables / disables the buffer interrupt (TXE / RXNE) of the modes using I2C interrupts -
 *        polling mode has no interrupt to be changed
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param bufState [in]: Required state, value from \ref i2c_FunctionState_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_BufIrq( i2c_PeriphId_t periphId, i2c_FunctionState_t bufState )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        const i2c_FunctionState_t irqUsed = I2c_Get_IrqUsed( &i2c_XferContext[ periphId ].Config );

        if( I2C_FUNCTION_ACTIVE != irqUsed )
        {
            /* Flags are polled */
            retState = I2C_REQUEST_OK;
        }
        else if( I2C_FUNCTION_ACTIVE == bufState )
        {
            retState = I2c_Isr_Set_ItActive( periphId, I2C_ISR_IT_BUF );
        }
        else
        {
            retState = I2c_Isr_Set_ItInactive( periphId, I2C_ISR_IT_BUF );
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Configures acknowledge control of the reception (CR1 ACK and POS) with read-back
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param ackBits  [in]: Required ACK / POS bits (0 - NACK without POS)
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Set_Ack( i2c_PeriphId_t periphId, uint32_t ackBits )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT > periphId                           ) &&
        ( 0u            == ( ackBits & ~I2C_CR1_ACK_MASK )    )    )
    {
        retState = I2c_Set_RegValue( &i2c_PeriphConf[ periphId ].PeriphReg->CR1, I2C_CR1_ACK_MASK, ackBits );
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Returns if the bytes of the running phase are moved by software (ISR / POLL mode, single
 *        byte read phase in DMA mode)
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return \ref I2C_FUNCTION_ACTIVE if the bytes are moved by software, otherwise
 *         \ref I2C_FUNCTION_INACTIVE
 */
static i2c_FunctionState_t I2c_Get_SwData( i2c_PeriphId_t periphId )
{
    i2c_FunctionState_t swData    = I2C_FUNCTION_INACTIVE;
    i2c_FunctionState_t dmaRxUsed = I2C_FUNCTION_INACTIVE;

    if( I2C_REQUEST_OK == I2c_Get_DmaRxUsed( periphId, &dmaRxUsed ) )
    {
        const i2c_XferContext_t * const xferCtx = &i2c_XferContext[ periphId ];

        if( ( I2C_XFER_MODE_DMA    != xferCtx->Config.XferMode ) ||
            ( ( I2C_XFER_PHASE_READ == xferCtx->Phase  ) &&
              ( I2C_FUNCTION_ACTIVE != dmaRxUsed       )    )    )
        {
            swData = I2C_FUNCTION_ACTIVE;
        }
        else
        {
            /* Bytes of the phase are moved by DMA */
        }
    }
    else
    {
        /* Invalid peripheral identification */
    }

    return ( swData );
}


/**
 * \brief Checks configuration of I2C_XFER_MODE_NONE (no mode specific resources)
 *
 * \param periphId   [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param dataConfig [in]: Pointer to data handling configuration. Must not be NULL.
 *
 * \return Returns \ref I2C_REQUEST_OK if the parameters are valid. Otherwise returns
 *         \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_None_Check_Config( i2c_PeriphId_t periphId, const i2c_DataConfig_t * const dataConfig )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT > periphId   ) &&
        ( I2C_NULL_PTR  != dataConfig )    )
    {
        retState = I2C_REQUEST_OK;
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Transfer mode handler without resources (NONE mode, CheckDone of ISR / POLL mode)
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Returns \ref I2C_REQUEST_OK for a valid periphId. Otherwise returns
 *         \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_None_Xfer( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        retState = I2C_REQUEST_OK;
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Checks that all bytes of the write phase were written to DR by software (ISR / POLL)
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Returns \ref I2C_REQUEST_OK if all bytes were written. Otherwise returns
 *         \ref I2C_REQUEST_ERROR.
 */
static i2c_RequestState_t I2c_Soft_Check_TxDone( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT                              > periphId                              ) &&
        ( i2c_XferContext[ periphId ].Request.TxSize <= i2c_XferContext[ periphId ].TxIdx     )    )
    {
        retState = I2C_REQUEST_OK;
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}

