/**
 * \author Mr.Nobody
 * \file I2c.c
 * \ingroup I2c
 * \brief Inter-Integrated Circuit (I2C) MCAL module common functionality
 *
 * The module drives STM32F4 I2C peripherals (I2C v1) in master mode:
 * - configuration: SCL frequency (CR2 FREQ, CCR and TRISE are calculated from PCLK1 and the
 *   I2C specification timings), analog / digital noise filter (devices with FLTR register),
 *   addressing mode, SCL / SDA pins
 * - transfers: write, read, write followed by read with repeated START and address only
 *   transfer (\ref i2c_XferRequest_t)
 *
 * I2C v1 has no hardware byte counter - the master transfer is sequenced by software for all
 * data transfer modes (I2c_Set_XferEvents, called with a snapshot of SR1):
 * - SB:     address byte (7-bit) or header (10-bit) is written to DR
 * - ADD10:  second byte of the 10-bit address is written to DR
 * - ADDR:   acknowledge control of the read phase is prepared (ACK / POS / STOP for 1, 2 and
 *           more bytes - RM procedure based on BTF) and ADDR is cleared
 * - TXE / RXNE / BTF: data bytes, end of the write phase (STOP or repeated START of the read
 *           phase), last bytes of the read phase (NACK programmed while SCL is stretched) -
 *           processed only after ADDR of the running phase (TXE / BTF of the write phase stay
 *           set until the repeated START is sent)
 * - AF:     NACK error, STOP condition is generated by software
 * - ARLO:   arbitration lost (bus is released by HW)
 * - BERR:   cleared and ignored in master mode (device errata: spurious bus error detection
 *           in master mode), reported if the peripheral is not master
 *
 * The transfer ends when the STOP condition is requested - the next transfer start waits until
 * the STOP condition is generated.
 *
 */
