/**
 * \brief Processes one sequencing step of the running transfer (all modes) from SR1 snapshot
 *
 * Priority of the events: arbitration lost, NACK, bus error, overrun, START sent (SB), 10-bit
 * header sent (ADD10), address acknowledged (ADDR), data step of the running phase (TXE / RXNE
 * / BTF). One step is processed per call - remaining flags are processed by the next interrupt
 * / task call.
 *
 * \note  If the transfer can not be continued (register verification failed), the transfer is
 *        aborted and \ref I2C_XFER_ERROR_BUS is reported.
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param isrFlags [in]: Snapshot of I2C SR1 register
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
i2c_RequestState_t I2c_Set_XferEvents( i2c_PeriphId_t periphId, i2c_IsrFlags_t isrFlags )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_PERIPH_CNT > periphId )
    {
        I2C_TypeDef * const       periphReg = i2c_PeriphConf[ periphId ].PeriphReg;
        i2c_XferContext_t * const xferCtx   = &i2c_XferContext[ periphId ];
        i2c_RequestState_t        stepState = I2C_REQUEST_OK;

        retState = I2C_REQUEST_OK;

        if( I2C_FUNCTION_ACTIVE != xferCtx->XferState )
        {
            /* No transfer is running */
        }
        else if( 0u != ( I2C_SR1_ARLO & isrFlags ) )
        {
            /* Arbitration lost - peripheral switched to slave mode, bus is released by HW */
            LL_I2C_ClearFlag_ARLO( periphReg );

            retState = I2c_Set_XferEnd( periphId, I2C_XFER_ERROR_ARBITRATION_LOST );
        }
        else if( 0u != ( I2C_SR1_AF & isrFlags ) )
        {
            /* NACK of address or data byte - STOP condition is generated by software */
            LL_I2C_ClearFlag_AF( periphReg );
            LL_I2C_GenerateStopCondition( periphReg );

            retState = I2c_Set_XferEnd( periphId, I2C_XFER_ERROR_NACK );
        }
        else if( 0u != ( I2C_SR1_BERR & isrFlags ) )
        {
            const uint32_t masterMode = LL_I2C_IsActiveFlag_MSL( periphReg );

            LL_I2C_ClearFlag_BERR( periphReg );

            if( 0u == masterMode )
            {
                /* Misplaced START / STOP lost the master mode - transfer can not be continued */
                retState = I2c_Set_XferError( periphId, I2C_XFER_ERROR_BUS );
            }
            else
            {
                /* Device errata: spurious bus error in master mode - the transfer is not disturbed */
            }
        }
        else if( 0u != ( I2C_SR1_OVR & isrFlags ) )
        {
            /* Overrun / underrun is not possible with clock stretching in master mode */
            LL_I2C_ClearFlag_OVR( periphReg );
        }
        else if( 0u != ( I2C_SR1_SB & isrFlags ) )
        {
            stepState = I2c_Set_XferAddrByte( periphId );
        }
        else if( 0u != ( I2C_SR1_ADD10 & isrFlags ) )
        {
            /* Second byte of the 10-bit address (ADD10 is cleared by SR1 read and DR write) */
            LL_I2C_TransmitData8( periphReg, (uint8_t)( xferCtx->Request.SlaveAddr & I2C_ADDR10_LOW_MASK ) );
        }
        else if( 0u != ( I2C_SR1_ADDR & isrFlags ) )
        {
            stepState = I2c_Set_XferAddrDone( periphId );
        }
        else if( I2C_FUNCTION_ACTIVE != xferCtx->AddrAcked )
        {
            /* TXE / BTF of the write phase stay set until the repeated START is sent - data flags
             * are valid after the address of the running phase is acknowledged */
        }
        else if( I2C_XFER_PHASE_WRITE == xferCtx->Phase )
        {
            stepState = I2c_Set_XferWriteStep( periphId, isrFlags );
        }
        else
        {
            stepState = I2c_Set_XferReadStep( periphId, isrFlags );
        }

        if( ( I2C_REQUEST_OK      != stepState          ) &&
            ( I2C_FUNCTION_ACTIVE == xferCtx->XferState )    )
        {
            /* Transfer can not be continued - peripheral is reset and error is reported */
            (void)I2c_Set_XferError( periphId, I2C_XFER_ERROR_BUS );
            retState = I2C_REQUEST_ERROR;
        }
        else if( I2C_REQUEST_OK != stepState )
        {
            /* Transfer was already ended and reported, its resources could not be released */
            retState = I2C_REQUEST_ERROR;
        }
        else
        {
            /* Event processed */
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Ends the read phase moved by DMA (receive stream transfer complete) - the last byte was
 *        received with NACK (LAST), STOP condition is requested and the transfer ends
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems (also if no DMA reception is running). Otherwise
 *         returns \ref I2C_REQUEST_ERROR.
 */
i2c_RequestState_t I2c_Set_XferRxDone( i2c_PeriphId_t periphId )
{
    i2c_RequestState_t  retState  = I2C_REQUEST_ERROR;
    i2c_FunctionState_t dmaRxUsed = I2C_FUNCTION_INACTIVE;

    retState = I2c_Get_DmaRxUsed( periphId, &dmaRxUsed );

    if( I2C_REQUEST_OK == retState )
    {
        const i2c_XferContext_t * const xferCtx = &i2c_XferContext[ periphId ];

        if( ( I2C_FUNCTION_ACTIVE == xferCtx->XferState ) &&
            ( I2C_XFER_PHASE_READ == xferCtx->Phase     ) &&
            ( I2C_FUNCTION_ACTIVE == dmaRxUsed          )    )
        {
            /* ACK cleared before STOP (no CR1 write while STOP is pending) - the last byte was
             * already received with NACK (LAST) */
            const i2c_RequestState_t ackState = I2c_Set_Ack( periphId, 0u );

            LL_I2C_GenerateStopCondition( i2c_PeriphConf[ periphId ].PeriphReg );

            retState = I2c_Set_XferEnd( periphId, I2C_XFER_ERROR_NONE );

            if( I2C_REQUEST_OK != ackState )
            {
                retState = I2C_REQUEST_ERROR;
            }
            else
            {
                /* Transfer ended */
            }
        }
        else
        {
            /* No DMA reception is running - spurious transfer complete is ignored */
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Terminates the running transfer by an error which is not a bus event (DMA error, failed
 *        transfer sequencing, bus error) - the transfer is aborted (software reset releases the
 *        stretched bus), the error is stored and ErrorCallback is called
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param errorId  [in]: Error identification, value from \ref i2c_XferErrorId_t (not NONE)
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
i2c_RequestState_t I2c_Set_XferError( i2c_PeriphId_t periphId, i2c_XferErrorId_t errorId )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT      > periphId ) &&
        ( I2C_XFER_ERROR_CNT  > errorId  ) &&
        ( I2C_XFER_ERROR_NONE != errorId )    )
    {
        i2c_XferContext_t * const xferCtx = &i2c_XferContext[ periphId ];

        if( I2C_FUNCTION_ACTIVE == xferCtx->XferState )
        {
            retState = I2c_Set_XferAbort( periphId );
        }
        else
        {
            /* Transfer already ended - error is only reported */
            retState = I2C_REQUEST_OK;
        }

        xferCtx->XferError = errorId;

        if( I2C_NULL_PTR != xferCtx->Config.ErrorCallback )
        {
            xferCtx->Config.ErrorCallback( errorId );
        }
        else
        {
            /* Error callback is not used */
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}

