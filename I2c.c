#define I2C_ADDR10_HEADER_MASK          ( 0x06u )

/** Mask of the second byte of the 10-bit address (address bits 7:0) */
#define I2C_ADDR10_LOW_MASK             ( 0xFFu )

/** Count of bytes of the read phase handled by BTF (N-2 and following bytes) */
#define I2C_RX_BTF_BYTES                ( 3u )

/** Count of last bytes of the read phase read after STOP is requested */
#define I2C_RX_LAST_BYTES               ( 2u )


/** Count of Hz in one MHz (FREQ field of CR2) */
#define I2C_HZ_PER_MHZ                  ( 1000000u )

/** Minimum PCLK1 frequency in MHz (Standard-mode) */
#define I2C_PCLK_MHZ_MIN                ( 2u )

/** Minimum PCLK1 frequency in MHz (Fast-mode) */
#define I2C_PCLK_MHZ_FAST_MIN           ( 4u )

/** Maximum allowed value of FREQ field of CR2 (50 MHz) */
#define I2C_PCLK_MHZ_MAX                ( 50u )

/** Maximum value of CCR field */
#define I2C_CCR_MAX                     ( 0xFFFu )

/** Count of picoseconds in one second */
