/**
 * \brief Configures SCL frequency - CR2 FREQ, CCR and TRISE are calculated from PCLK1 and the
 *        I2C specification timings of the speed mode
 *
 * \note  Speed mode is derived from the frequency: up to 100 kHz Standard-mode, up to 400 kHz
 *        Fast-mode (duty cycle 2 or 16/9 with the smaller frequency error). The resulting
 *        frequency never exceeds the required one and differs from it by
 *        I2C_BUS_FREQ_TOLERANCE_PCT at most. PCLK1 must be 2 - 50 MHz (Fast-mode 4 - 50 MHz).
 *
 * \note  Device errata: repeated START setup time (tSU;STA) may be violated in Standard-mode
 *        between 88 and 100 kHz - use up to 88 kHz or Fast-mode for repeated START transfers
 *        with strict slaves.
 *
 * \pre   Peripheral must be disabled (PE = 0). Otherwise \ref I2C_REQUEST_ERROR is returned
 *        and no register is modified.
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param busFreq  [in]: Required SCL frequency in Hz (1 - \ref I2C_BUS_FREQ_MAX_HZ)
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise (also if the frequency can not be reached
 *         with PCLK1) returns \ref I2C_REQUEST_ERROR.
 */
i2c_RequestState_t I2c_Set_BusFreq( i2c_PeriphId_t periphId, i2c_FreqHz_t busFreq )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    retState = I2c_Check_PeriphDisabled( periphId );

    if( I2C_REQUEST_OK == retState )
    {
        I2C_TypeDef * const periphReg = i2c_PeriphConf[ periphId ].PeriphReg;
        i2c_FreqHz_t        clkFreq   = 0u;
        uint32_t            ccrReg    = 0u;
        uint32_t            triseReg  = 0u;

        retState = I2c_Get_PeriphClk( periphId, &clkFreq );

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Get_ClkRegs( clkFreq, busFreq, &ccrReg, &triseReg );
        }
        else
        {
            /* Peripheral clock frequency is not available */
        }

        /* FREQ must equal PCLK1 in MHz - data hold / setup timings are derived from it */
        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->CR2, I2C_CR2_FREQ, ( clkFreq / I2C_HZ_PER_MHZ ) );
        }
        else
        {
            /* Frequency can not be reached, timing is not modified */
        }

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->CCR, ( I2C_CCR_FS | I2C_CCR_DUTY | I2C_CCR_CCR ), ccrReg );
        }
        else
        {
            /* FREQ configuration failed */
        }

        if( I2C_REQUEST_OK == retState )
        {
            retState = I2c_Set_RegValue( &periphReg->TRISE, I2C_TRISE_TRISE, triseReg );
        }
        else
        {
            /* CCR configuration failed */
        }
    }
    else
    {
        /* Peripheral is enabled (or invalid ID), timing change is not allowed */
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Returns SCL frequency calculated from CCR and PCLK1
 *
 * \note  The value is the nominal frequency - real SCL frequency is lower by the rise time of
 *        the bus (SCL high period is counted from the detected rising edge) and by clock
 *        stretching of the slaves.
 *
 * \param periphId [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param busFreq [out]: Pointer to store the SCL frequency in Hz. Must not be NULL.
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise (also if SCL timing is not configured)
 *         returns \ref I2C_REQUEST_ERROR.
 */
i2c_RequestState_t I2c_Get_BusFreq( i2c_PeriphId_t periphId, i2c_FreqHz_t * const busFreq )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( ( I2C_PERIPH_CNT > periphId ) &&
        ( I2C_NULL_PTR  != busFreq  )    )
    {
        I2C_TypeDef * const periphReg = i2c_PeriphConf[ periphId ].PeriphReg;
        i2c_FreqHz_t        clkFreq   = 0u;

        retState = I2c_Get_PeriphClk( periphId, &clkFreq );

        if( I2C_REQUEST_OK == retState )
        {
            const uint32_t        ccrMode  = READ_BIT( periphReg->CCR, ( I2C_CCR_FS | I2C_CCR_DUTY ) );
            const i2c_TimingCnt_t ccrValue = READ_BIT( periphReg->CCR, I2C_CCR_CCR );

            retState = I2C_REQUEST_ERROR;

            for( i2c_SclMode_t modeIdx = I2C_SCL_MODE_STANDARD; I2C_SCL_MODE_CNT > modeIdx; modeIdx ++ )
            {
                const i2c_SclCharac_t * const charac = &i2c_SclCharacLut[ modeIdx ];

                if( ( charac->CcrMode == ccrMode  ) &&
                    ( 0u               < ccrValue )    )
                {
                    const i2c_TimingCnt_t sclCycles = ( charac->LowCycles + charac->HighCycles ) * ccrValue;

                    *busFreq = (i2c_FreqHz_t)I2C_DIV_ROUND_NEAREST( clkFreq, sclCycles );
                    retState = I2C_REQUEST_OK;
                    break;
                }
                else
                {
                    /* SCL generation option does not match (or CCR is not configured) */
                }
            }
        }
        else
        {
            /* Peripheral clock frequency is not available */
        }
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


/**
 * \brief Enables / disables analog noise filter
 *
 * \note  Devices without FLTR register accept only \ref I2C_ANALOG_FILTER_DISABLED (no register
 *        is modified).
 *
 * \pre   Peripheral must be disabled (PE = 0). Otherwise \ref I2C_REQUEST_ERROR is returned
 *        and no register is modified.
 *
 * \param periphId     [in]: I2C peripheral identification, value from \ref i2c_PeriphId_t
 * \param analogFilter [in]: Required filter state, value from \ref i2c_AnalogFilter_t
 *
 * \return Function processing state. Returns \ref I2C_REQUEST_OK if request
 *         was processed without problems. Otherwise returns \ref I2C_REQUEST_ERROR.
 */
i2c_RequestState_t I2c_Set_AnalogFilter( i2c_PeriphId_t periphId, i2c_AnalogFilter_t analogFilter )
{
    i2c_RequestState_t retState = I2C_REQUEST_ERROR;

    if( I2C_ANALOG_FILTER_CNT > analogFilter )
    {
        retState = I2c_Check_PeriphDisabled( periphId );
    }
    else
    {
        retState = I2C_REQUEST_ERROR;
    }

    if( I2C_REQUEST_OK == retState )
    {
#if defined(I2C_FLTR_ANOFF)
        uint32_t anoffBit = 0u;

        if( I2C_ANALOG_FILTER_DISABLED == analogFilter )
        {
            anoffBit = I2C_FLTR_ANOFF;
        }
        else
        {
            /* ANOFF = 0 - filter enabled */
        }

        /* LL_I2C_IsEnabledAnalogFilter() of STM32F4 LL returns inverted state - ANOFF is accessed directly */
        retState = I2c_Set_RegValue( &i2c_PeriphConf[ periphId ].PeriphReg->FLTR, I2C_FLTR_ANOFF, anoffBit );
#else
        if( I2C_ANALOG_FILTER_DISABLED == analogFilter )
        {
            retState = I2C_REQUEST_OK;
        }
        else
        {
            /* Device has no configurable analog filter */
            retState = I2C_REQUEST_ERROR;
        }
#endif
    }
    else
    {
        /* Invalid parameter or peripheral is enabled, configuration change is not allowed */
        retState = I2C_REQUEST_ERROR;
    }

    return ( retState );
}


